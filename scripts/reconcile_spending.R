# scripts/reconcile_spending.R
setwd("C:/Users/SAMEER/OneDrive/Desktop/Prob_Proj")
source("R/benford.R")

cat("=== RECONCILING USASPENDING BENFORD STATISTICS ===\n\n")
raw <- readr::read_csv("data/raw/usaspending/usaspending.csv", 
                       col_types = readr::cols_only(federal_action_obligation = readr::col_double()))
vals <- raw[["federal_action_obligation"]]

# 1. Strictly positive obligations only (N = 81,277)
pos <- vals[!is.na(vals) & vals > 0]
t1 <- benford_test_values(pos, kind = "first")
cat(sprintf("[DATASET 1: USASPENDING TRANSACTION OBLIGATIONS (STRICTLY POSITIVE)]\n"))
cat(sprintf("  Description: Positive-only values of federal_action_obligation in usaspending.csv\n"))
cat(sprintf("  Sample Size (N):   %d\n", t1$N))
cat(sprintf("  Chi-Square (X2):   %.4f\n", t1$x2))
cat(sprintf("  Degrees of Freedom: %d\n", t1$df))
cat(sprintf("  p-value:           %.4e\n", t1$p))
cat(sprintf("  MAD:               %.6f\n", t1$mad))
cat(sprintf("  Nigrini Band:      %s\n", t1$band))
cat(sprintf("  Cohen's w:         %.4f\n", t1$cohen_w))
cat(sprintf("  Validity Tier:     %s\n", t1$tier))
cat("  Observed Counts:   [", paste(t1$observed, collapse=", "), "]\n")
cat("  Expected Counts:   [", paste(round(t1$E, 2), collapse=", "), "]\n")
cat("  Std Residuals:     [", paste(round(t1$residuals, 2), collapse=", "), "]\n\n")

# 2. Non-zero obligations (positive + absolute value of negatives)
non_zero <- abs(vals[!is.na(vals) & vals != 0])
t2 <- benford_test_values(non_zero, kind = "first")
cat(sprintf("[DATASET 2: USASPENDING OBLIGATIONS (POSITIVE + ABSOLUTE NEGATIVES)]\n"))
cat(sprintf("  Description: All non-zero amounts |federal_action_obligation| (81,277 positive + 20,104 de-obligations)\n"))
cat(sprintf("  Sample Size (N):   %d\n", t2$N))
cat(sprintf("  Chi-Square (X2):   %.4f\n", t2$x2))
cat(sprintf("  Degrees of Freedom: %d\n", t2$df))
cat(sprintf("  p-value:           %.4e\n", t2$p))
cat(sprintf("  MAD:               %.6f\n", t2$mad))
cat(sprintf("  Nigrini Band:      %s\n", t2$band))
cat(sprintf("  Cohen's w:         %.4f\n", t2$cohen_w))
cat("  Observed Counts:   [", paste(t2$observed, collapse=", "), "]\n")
cat("  Expected Counts:   [", paste(round(t2$E, 2), collapse=", "), "]\n")
cat("  Std Residuals:     [", paste(round(t2$residuals, 2), collapse=", "), "]\n\n")

# 3. Pipeline indicator: USASPEND.FEDERAL_ACTION_OBLIGATION
panel <- load_usaspending("data/raw/usaspending")
fao_panel <- panel[panel[["indicator_code"]] == "USASPEND.FEDERAL_ACTION_OBLIGATION", ]
t3 <- benford_test_values(fao_panel[["value"]], kind = "first")
cat(sprintf("[DATASET 3: PIPELINE USASPEND.FEDERAL_ACTION_OBLIGATION (chi_square_results.csv)]\n"))
cat(sprintf("  Sample Size (N):   %d\n", t3$N))
cat(sprintf("  Chi-Square (X2):   %.4f\n", t3$x2))
cat(sprintf("  Degrees of Freedom: %d\n", t3$df))
cat(sprintf("  p-value:           %.4e\n", t3$p))
cat(sprintf("  MAD:               %.6f\n", t3$mad))
cat(sprintf("  Nigrini Band:      %s\n\n", t3$band))

